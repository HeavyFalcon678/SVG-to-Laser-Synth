function calculateInitialPositions(coordinates, valueArray) {
  let constantArray = []
  valueArray.forEach((value) => {
    constantArray.push(calculateConstant(coordinates, value))
  });
  return constantArray;
}


function calculateConstant(coordinates, currentValue) {
  let total = coordinates.reduce((acc, val, index) => {
    let currentTime = calculateTime(index, coordinates.length)
    let currentVector = calculateVector(currentValue, currentTime);
    let currentCoord = math.complex(val[0], val[1]);
    acc = math.add(acc, math.multiply(currentCoord, currentVector))
    return acc;
  }, math.complex(0, 0));

  const constant = math.divide(total, coordinates.length)
  return constant;
}


// calculates the vector for a certain value and time
function calculateVector(n, t) {
  const nNeg2piT = n * -2 * Math.PI * t
  return math.complex(Math.cos(nNeg2piT), Math.sin(nNeg2piT));
}

function calculateTime(valueIndex, totalPoints) {
  return math.divide(valueIndex, totalPoints)
}

function getStartingAngle(constant) {
  const re = constant.re;
  const im = constant.im;

  return Math.atan2(im, re);
}

function getRadius(constant) {
  const re = constant.re;
  const im = constant.im;

  return Math.sqrt((re**2) + (im**2))
}

function getAngle(n, t) {
  return 2 * Math.PI * n * t;
}

function drawArrow(base, vec, myColor) {
  push();
  stroke(myColor);
  strokeWeight(3);
  fill(myColor);
  translate(base.x, base.y);
  line(0, 0, vec.x, vec.y);
  rotate(vec.heading());
  let arrowSize = 7;
  translate(vec.mag() - arrowSize, 0);
  triangle(0, arrowSize / 2, 0, -arrowSize / 2, arrowSize, 0);
  pop();
}

