function setup() {
  constantArray = calculateInitialPositions(coordinates, valueArray)
  console.log(constantArray)

  createCanvas(canvasWidth, canvasHeight);

  let audioCtx = new (window.AudioContext || window.webkitAudioContext)();
  let scriptNode = audioCtx.createScriptProcessor(2048, 1, 1);

  let audioT = 0;

  scriptNode.onaudioprocess = function(audioProcessingEvent) {
    let output = audioProcessingEvent.outputBuffer.getChannelData(0);

    for (let i = 0; i < output.length; i++) {
      let sample = 0;

      // Sum Fourier tones
      constantArray.forEach((constant, index) => {
        const n = valueArray[index];
        const amplitude = getRadius(constant) * 0.01; // scale down volume
        const phase = getStartingAngle(constant);
        const basePitch = 400; // change this number for pitch
        sample += amplitude * Math.sin(2 * Math.PI * n * basePitch * audioT + phase);
        const gain = 2.0; // try values between 0.5 and 5

        sample += gain * amplitude * Math.sin(2 * Math.PI * n * basePitch * audioT + phase);


      });

      output[i] = sample;
      audioT += 1 / audioCtx.sampleRate;
    }
  };

  scriptNode.connect(audioCtx.destination);
}

